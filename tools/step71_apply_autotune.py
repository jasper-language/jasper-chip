# -*- coding: utf-8 -*-
"""Step71: Apply Step70's recommended link depths into a stable, importable module.

Why:
  - Step70 produces a machine-readable JSON with recommended (card_link_depth, reloc_link_depth).
  - Step71 turns that into a *code artifact* (rtl/autotuned_link_depths.py) that simulation harnesses
    and future steps can import as a default knob, without hard-coding report paths.

Artifacts (defaults):
  - Input:  reports/step70_recommended_depths.json
  - Output: rtl/autotuned_link_depths.py
  - Output: reports/step71_applied_depths.json (copy, optional)

Usage:
  python -m tools.step71_apply_autotune
  python -m tools.step71_apply_autotune --in-json reports/step70_recommended_depths.json --out-py rtl/autotuned_link_depths.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_IN_JSON = Path("reports/step70_recommended_depths.json")
DEFAULT_OUT_PY = Path("rtl/autotuned_link_depths.py")
DEFAULT_OUT_JSON = Path("reports/step71_applied_depths.json")


def apply_autotune(in_json: Path = DEFAULT_IN_JSON,
                  out_py: Path = DEFAULT_OUT_PY,
                  out_json: Path | None = DEFAULT_OUT_JSON) -> dict:
    """Apply recommended depths from JSON into a python module.

    Returns the payload dict that was applied.
    """
    payload = json.loads(Path(in_json).read_text(encoding="utf-8"))
    card = int(payload.get("card_link_depth", 0))
    reloc = int(payload.get("reloc_link_depth", 0))
    ok = int(payload.get("ok", 0))
    if ok != 1 or card <= 0 or reloc <= 0:
        raise ValueError(f"step71: invalid recommendation payload: {payload}")

    out_py = Path(out_py)
    out_py.parent.mkdir(parents=True, exist_ok=True)
    out_py.write_text(
        """# -*- coding: utf-8 -*-
\"\"\"Autotuned inter-chip link depth parameters.

Generated by: tools.step71_apply_autotune

Do NOT edit manually. Re-run step70/step71 instead.
\"\"\"

VALID = 1
CARD_LINK_DEPTH = {card}
RELOC_LINK_DEPTH = {reloc}
""".format(card=card, reloc=reloc),
        encoding="utf-8",
    )

    if out_json is not None:
        out_json = Path(out_json)
        out_json.parent.mkdir(parents=True, exist_ok=True)
        out_json.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    return {"ok": 1, "card_link_depth": card, "reloc_link_depth": reloc}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in-json", default=str(DEFAULT_IN_JSON), help="Input recommended JSON from step70")
    ap.add_argument("--out-py", default=str(DEFAULT_OUT_PY), help="Output python module path")
    ap.add_argument("--out-json", default=str(DEFAULT_OUT_JSON), help="Output JSON copy (or empty to disable)")
    args = ap.parse_args()

    out_json = Path(args.out_json) if str(args.out_json).strip() else None
    payload = apply_autotune(Path(args.in_json), Path(args.out_py), out_json=out_json)
    print("OK:", payload)


if __name__ == "__main__":
    main()
